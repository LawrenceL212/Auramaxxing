/* Regenerates lib/exercise-scale.js from ../exercises.js.
   Scoring only needs to know which intensity scale an exercise logs on, which
   is decided by `timed`, `timedUnit` and `intent` — nothing else. Projecting
   just those three keeps the duplicated surface as small as possible.

   Run after ANY change to exercises.js:   node generate-exercise-scale.mjs
*/
import { BASE_EXERCISES } from '../exercises.js';
import fs from 'fs';

const out = {};
for (const [name, d] of Object.entries(BASE_EXERCISES)) {
  const e = {};
  if (d.timed) e.timed = true;
  if (d.timedUnit) e.timedUnit = d.timedUnit;
  if (d.intent) e.intent = d.intent;
  out[name] = e;
}
const body = `// GENERATED by generate-exercise-scale.mjs — do not edit by hand.
// Source: ../exercises.js  ·  ${Object.keys(out).length} exercises
// Only the fields that decide RIR-vs-RPE scale are projected here.
'use strict';
module.exports = ${JSON.stringify(out, null, 0)};
`;
fs.writeFileSync(new URL('./lib/exercise-scale.js', import.meta.url), body, 'utf8');
console.log('wrote lib/exercise-scale.js with ' + Object.keys(out).length + ' exercises');
